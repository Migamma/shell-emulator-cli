package org.example.command;

/**
 * Команда эмулятора оболочки.
 * <p>
 * Команда не печатает результат сама, а возвращает его терминалу
 * в виде {@link CommandResult}.
 */
public interface Command {
    /**
     * Выполняет команду с заданными аргументами.
     *
     * @param args аргументы команды, без её имени
     * @return результат выполнения: текст для вывода, признак успеха
     * и признак завершения работы
     */
    CommandResult execute(String[] args);

}
